<?php
declare(strict_types=1);

namespace Organilog;

/** Shared installation engine for the browser wizard and the optional CLI. */
final class Setup
{
    public static function assertRequirements(): void
    {
        if (PHP_VERSION_ID < 80100) {
            throw new \RuntimeException('PHP 8.1 or newer is required.');
        }
        foreach (['curl', 'mbstring', 'json'] as $extension) {
            if (!extension_loaded($extension)) {
                throw new \RuntimeException("Enable the PHP $extension extension, then try again.");
            }
        }
    }

    /** Returns the new admin secret once; refuses to replace an existing configuration. */
    public static function install(string $root, string $account, string $token, ?string $configFile = null, array $options = []): string
    {
        self::assertRequirements();
        $file = $configFile ?? $root . '/config.php';
        if (file_exists($file) || is_link($file)) {
            throw new \RuntimeException('config.php already exists; setup will not overwrite it. Use --check to inspect the installation.');
        }
        $config = require $root . '/config.example.php';
        $config['organilog']['account'] = trim($account);
        $config['organilog']['token'] = trim($token);
        $secret = KeyStore::generate();
        $config['admin_key_sha256'] = hash('sha256', $secret);
        if (isset($options['branding'])) {
            $config['branding'] = $options['branding'];
        }
        $config = Configuration::validate($config);
        self::checkCatalog($root);
        self::checkStorage($root);

        // Exclusive creation protects existing installations, including concurrent setup runs.
        $mask = umask(0077);
        try {
            $handle = @fopen($file, 'x+b');
        } finally {
            umask($mask);
        }
        if ($handle === false) {
            throw new \RuntimeException('Cannot create config.php. Check directory permissions and whether setup has already run.');
        }
        $contents = "<?php\n// Generated by bin/setup.php. Keep this file private.\nreturn " . var_export($config, true) . ";\n";
        try {
            if (fwrite($handle, $contents) !== strlen($contents) || !fflush($handle)) {
                throw new \RuntimeException('Could not write config.php completely. Check free disk space and try again.');
            }
        } catch (\Throwable $e) {
            fclose($handle);
            unlink($file);
            throw $e;
        }
        fclose($handle);
        return $secret;
    }

    public static function check(string $root, ?string $configFile = null): array
    {
        self::assertRequirements();
        $file = $configFile ?? $root . '/config.php';
        if (!is_file($file)) {
            throw new \RuntimeException('config.php is missing. Run php bin/setup.php first.');
        }
        $config = Configuration::validate(require $file);
        self::checkCatalog($root);
        self::checkStorage($root);
        return [
            'PHP ' . PHP_VERSION . ': curl, mbstring, json available',
            'Configuration and endpoint catalog valid',
            'Runtime storage writable',
            'Upstream writes ' . ($config['allow_writes'] ? 'enabled' : 'disabled'),
            'Write body logging ' . ($config['log_write_bodies'] ? 'enabled' : 'disabled'),
            'No request was made to Organilog; account credentials were not verified.',
        ];
    }

    private static function checkCatalog(string $root): void
    {
        $file = $root . '/data/catalog.json';
        if (!is_readable($file)) {
            throw new \RuntimeException('data/catalog.json is missing or unreadable. Restore it from the repository.');
        }
        $data = json_decode((string) file_get_contents($file), true, 512, JSON_THROW_ON_ERROR);
        if (!is_array($data) || empty($data['entities']) || empty($data['endpoints'])
            || !is_array($data['entities']) || !is_array($data['endpoints'])) {
            throw new \RuntimeException('data/catalog.json must contain entities and endpoints.');
        }
        foreach ($data['endpoints'] as $endpoint) {
            if (!is_array($endpoint) || !is_string($endpoint['id'] ?? null)
                || !is_string($endpoint['entity'] ?? null) || !is_string($endpoint['action'] ?? null)
                || !in_array($endpoint['kind'] ?? null, Catalog::KINDS, true)) {
                throw new \RuntimeException('data/catalog.json contains an invalid endpoint.');
            }
        }
    }

    private static function checkStorage(string $root): void
    {
        foreach (['var', 'var/usage', 'var/logs'] as $sub) {
            $dir = $root . '/' . $sub;
            if (!is_dir($dir) && !@mkdir($dir, 0750, true) && !is_dir($dir)) {
                throw new \RuntimeException("Cannot create $sub. Give the PHP user write access to var/.");
            }
            $probe = $dir . '/.setup-' . bin2hex(random_bytes(8));
            $handle = @fopen($probe, 'x+b');
            if ($handle === false) {
                throw new \RuntimeException("$sub is not writable by this PHP user.");
            }
            try {
                if (!flock($handle, LOCK_EX) || fwrite($handle, 'check') !== 5 || !fflush($handle)) {
                    throw new \RuntimeException("$sub must support file writes and locks.");
                }
            } finally {
                fclose($handle);
                unlink($probe);
            }
        }
        if (file_exists($root . '/var/keys.json')) {
            if (!is_writable($root . '/var/keys.json')) {
                throw new \RuntimeException('var/keys.json is not writable by this PHP user.');
            }
            JsonFile::read($root . '/var/keys.json');
        }
    }
}
