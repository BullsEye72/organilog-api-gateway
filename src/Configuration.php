<?php
declare(strict_types=1);

namespace Organilog;

/** Shared by the installer, configuration check, and API. Never includes secret values in errors. */
final class Configuration
{
    public static function validate(mixed $config): array
    {
        if (!is_array($config) || !is_array($config['organilog'] ?? null)) {
            throw new \RuntimeException('config.php must return an array with an organilog section.');
        }
        foreach (['account', 'token'] as $field) {
            if (!is_string($config['organilog'][$field] ?? null) || trim($config['organilog'][$field]) === '') {
                throw new \RuntimeException("Set organilog.$field in config.php.");
            }
        }
        $config['organilog'] += [
            'base_url' => 'https://sync.organilog.com/api/v3', 'timeout' => 30,
            'connect_timeout' => 5, 'retry_reads' => false, 'failure_threshold' => 2, 'cooldown_seconds' => 60,
        ];
        $url = $config['organilog']['base_url'];
        $parts = is_string($url) ? parse_url($url) : false;
        if ($parts === false || ($parts['scheme'] ?? '') !== 'https' || empty($parts['host'])
            || isset($parts['user']) || isset($parts['pass']) || isset($parts['query']) || isset($parts['fragment'])) {
            throw new \RuntimeException('organilog.base_url must be an HTTPS URL without credentials, query, or fragment.');
        }
        $timeout = $config['organilog']['timeout'];
        if (!is_int($timeout) || $timeout < 1 || $timeout > 300) {
            throw new \RuntimeException('organilog.timeout must be an integer from 1 to 300 seconds.');
        }
        foreach (['connect_timeout' => 300, 'failure_threshold' => 1000, 'cooldown_seconds' => 604800] as $field => $max) {
            $value = $config['organilog'][$field];
            if (!is_int($value) || $value < 1 || $value > $max) {
                throw new \RuntimeException("organilog.$field must be an integer from 1 to $max.");
            }
        }
        if (!is_bool($config['organilog']['retry_reads'])) {
            throw new \RuntimeException('organilog.retry_reads must be true or false.');
        }
        if (!is_string($config['admin_key_sha256'] ?? null)
            || !preg_match('/^[a-f0-9]{64}$/D', $config['admin_key_sha256'])) {
            throw new \RuntimeException('Set admin_key_sha256 to the SHA-256 hash generated by setup.php or keygen.php.');
        }
        $config += ['allow_writes' => false, 'verify_updates' => true, 'log_write_bodies' => false];
        foreach (['allow_writes', 'verify_updates', 'log_write_bodies'] as $field) {
            if (!is_bool($config[$field])) {
                throw new \RuntimeException("$field must be true or false in config.php.");
            }
        }
        $config += ['branding' => ['name' => 'Organilog API', 'logo' => null]];
        if (!is_array($config['branding']) || !is_string($config['branding']['name'] ?? null)
            || trim($config['branding']['name']) === '' || mb_strlen($config['branding']['name']) > 80) {
            throw new \RuntimeException('The application name must be between 1 and 80 characters.');
        }
        $logo = $config['branding']['logo'] ?? null;
        if ($logo !== null && (!is_string($logo) || !preg_match('/^logo-[a-f0-9]{32}\.(png|jpg|webp)$/D', $logo))) {
            throw new \RuntimeException('The logo file name is invalid.');
        }
        return $config;
    }
}
